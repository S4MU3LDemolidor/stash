import AppKit
import UniformTypeIdentifiers

/// Knows when the clipboard last changed, by polling `changeCount` (cheap; the contents
/// are only read when Capture opens).
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private let pasteboard: NSPasteboard
    private var changeCount: Int
    private var timer: Timer?
    private(set) var lastChange: Date?
    /// Clipboard contents Stash put there itself (e.g. Copy Link), which Capture shouldn't offer.
    private var ownChangeCount: Int?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        changeCount = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Whether the clipboard changed within the last `window` seconds (never, if `window` is 0).
    func changed(within window: TimeInterval) -> Bool {
        poll()
        guard window > 0, let lastChange, pasteboard.changeCount != ownChangeCount else { return false }
        return Date().timeIntervalSince(lastChange) <= window
    }

    func ignoreCurrentContents() {
        poll()
        ownChangeCount = pasteboard.changeCount
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        lastChange = Date()
    }
}

/// Turns pasteboard contents (clipboard, paste or drop) into something Capture can save.
enum ClipboardReader {
    /// Password managers and similar apps mark secrets with these (nspasteboard.org). Never capture them.
    static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private static let imageTypes: [(NSPasteboard.PasteboardType, String)] = [
        (.png, "png"),
        (.init(UTType.jpeg.identifier), "jpg"),
        (.init(UTType.heic.identifier), "heic"),
        (.init(UTType.gif.identifier), "gif"),
        (.init(UTType.webP.identifier), "webp"),
        (.tiff, "tiff"),
    ]

    /// Types to register for drag and drop.
    static var acceptedTypes: [NSPasteboard.PasteboardType] {
        [.fileURL, .URL, .string] + imageTypes.map(\.0)
    }

    static func content(of pasteboard: NSPasteboard) -> CaptureContent? {
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: privateTypes) else { return nil }

        // Files copied in Finder (or dropped). Folders aren't supported.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let file = urls.first(where: { !$0.hasDirectoryPath }) {
            return .file(file)
        }

        let string = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines)
        let stringURL = string.flatMap(webURL)

        // An image wins unless there's also real text: "Copy Image" in a browser adds at most
        // the image's URL, while spreadsheets copy cells as text plus a picture of them.
        if string?.isEmpty != false || stringURL != nil, let image = image(in: pasteboard) {
            return image
        }
        if let stringURL {
            return .link(stringURL, title: nil, timestamp: nil)
        }
        if let string, !string.isEmpty {
            return .text(string)
        }
        if let url = NSURL(from: pasteboard) as URL?, let webURL = webURL(url.absoluteString) {
            return .link(webURL, title: nil, timestamp: nil)
        }
        return nil
    }

    /// A single http(s) URL, nothing else.
    static func webURL(_ string: String) -> URL? {
        guard !string.contains(where: \.isWhitespace),
              let url = URL(string: string),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
              url.host(percentEncoded: false)?.isEmpty == false
        else { return nil }
        return url
    }

    private static func image(in pasteboard: NSPasteboard) -> CaptureContent? {
        for (type, fileExtension) in imageTypes {
            guard let data = pasteboard.data(forType: type) else { continue }
            // TIFF is what screenshots and many apps put on the clipboard; store it as PNG.
            if type == .tiff {
                guard let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) else { continue }
                return .image(png, fileExtension: "png")
            }
            return .image(data, fileExtension: fileExtension)
        }
        return nil
    }
}
